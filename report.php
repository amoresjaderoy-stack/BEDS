<?php $report = beds_find($db["reports"], "report_id", $id);
$modalTitle = $report
    ? "Report #" . str_pad((string) $id, 3, "0", STR_PAD_LEFT) . " Preview"
    : "Report Preview";
include __DIR__ . "/modal_header.php";
$inRange = $report
    ? array_values(
        array_filter(
            $db["incidents"],
            static fn(array $incident): bool => substr(
                $incident["date_reported"],
                0,
                10,
            ) >= $report["date_range_start"] &&
                substr($incident["date_reported"], 0, 10) <=
                    $report["date_range_end"],
        ),
    )
    : [];
$byType = array_fill_keys(BEDS_INCIDENT_TYPES, 0);
foreach ($inRange as $incident) {
    $byType[$incident["incident_type"]] =
        ($byType[$incident["incident_type"]] ?? 0) + 1;
}
$byStatus = array_fill_keys(BEDS_STATUS_FLOW, 0);
foreach ($inRange as $incident) {
    $byStatus[$incident["status"]] = ($byStatus[$incident["status"]] ?? 0) + 1;
}
?>
<div class="modal-body"><div class="report-preview">BARANGAY LIBERTAD, BOGO CITY — EMERGENCY DISPATCH REPORT
Report Type : <?= BedsHelper::e($report["report_type"] ?? "—") ?>
Period      : <?= BedsHelper::e(
    $report["date_range_start"] ?? "—",
) ?> to <?= BedsHelper::e($report["date_range_end"] ?? "—") ?>
Generated by: <?= BedsHelper::e(
    BedsHelper::userName($db, $report["generated_by"] ?? 0),
) ?>
Generated on: <?= BedsHelper::e($report["date_generated"] ?? "—") ?>
----------------------------------------------
TOTAL INCIDENTS       : <?= (int) ($report["total_incidents"] ?? 0) ?>
AVG RESPONSE TIME      : <?= BedsHelper::e(
    $report["avg_response_time"] ?? "N/A",
) ?>
----------------------------------------------
BY INCIDENT TYPE
<?php foreach ($byType as $type => $count): ?>  <?= BedsHelper::e(
      str_pad($type, 24, "."),
  ) ?> <?= (int) $count ?>
<?php endforeach; ?>----------------------------------------------
BY STATUS
<?php foreach ($byStatus as $status => $count): ?>  <?= BedsHelper::e(
      str_pad($status, 24, "."),
  ) ?> <?= (int) $count ?>
<?php endforeach; ?>----------------------------------------------
For submission to the Cebu City Disaster Risk
Reduction and Management Office (CCDRRMO).</div></div><div class="modal-foot"><a class="btn btn-sm btn-ghost" href="<?= BedsHelper::e(
    BedsHelper::redirect("reports"),
) ?>">Close</a></div>
